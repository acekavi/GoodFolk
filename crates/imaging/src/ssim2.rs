const VERT_MUL_PREV_3: f32 = -1.1755705;
const VERT_MUL_PREV_5: f32 = -0.000_000_000_000_000_122_464_69;
const MUL_IN_1: f32 = 0.055295236;
const MUL_IN_3: f32 = -0.058836687;
const MUL_IN_5: f32 = 0.012955819;
