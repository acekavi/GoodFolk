//! Exact SSIMULACRA2 in parallel row bands.
//!
//! The score is a function of per-scale sums over the whole image, and every term of those sums
//! depends on a pixel and its neighbours within the blur radius. So each scale is cut into bands of
//! rows; a band reads a few rows of halo, computes its partial sums, and the bands' sums are added.
//! The recursive Gaussian is a truncated cosine filter: zero state at the top of a band's halo gives
//! the same output as running from the top of the image.

use std::sync::OnceLock;

use image::RgbaImage;
use rayon::prelude::*;
use yuvxyb::{ColorPrimaries, LinearRgb, Rgb, TransferCharacteristic, Xyb};

// How often to downscale and score the input images. Each step downscales by a factor of two.
const NUM_SCALES: usize = 6;
/// Rows scored per band. The halo costs about `(RADIUS * 2) / BAND_ROWS` extra work. The recursive filter is
/// only periodic to single precision, so a band that restarts it from zero state differs from one long
/// run by an error that shrinks with the band height: 0.046 at 16 rows, 0.027 at 64, 0.007 at 256 and 0.001 at 512 (SSIMULACRA2 points, 2400 px).
const BAND_ROWS: usize = 512;
/// Columns the vertical blur handles at once.
const COLUMNS: usize = 32;
/// Transparent pixels are scored over this grey, so the colour hidden behind them does not count.
const BACKDROP: f32 = 128.0;

// Recursive Gaussian (sigma 1.5) constants, as generated by the ssimulacra2 build script.
const RADIUS: usize = 5;
const VERT_MUL_IN_1: f32 = 0.055295236;
const VERT_MUL_IN_3: f32 = -0.058836687;
