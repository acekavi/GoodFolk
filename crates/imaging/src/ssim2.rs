/// `a * b + c` with one rounding, as the original computes it. The recursive filter amplifies rounding
/// differences (plain arithmetic moves a score by up to about 0.2), so the port keeps the fused form; the
/// workspace targets x86-64-v3, where it is a single FMA instruction.
#[inline(always)]
fn fma(a: f32, b: f32, c: f32) -> f32 {
    a.mul_add(b, c)
}

/// Pixels as linear RGB.
struct Linear {
    data: Vec<[f32; 3]>,
    width: usize,
    height: usize,
}

/// The XYB planes of one scale.
struct Planes {
    width: usize,
    height: usize,
    planes: [Vec<f32>; 3],
}

/// The reference image of a comparison, prepared once so many distorted versions can be scored
/// against it. It holds the XYB planes of every scale (about 16 bytes per pixel).
pub struct Reference {
    width: usize,
    height: usize,
    scales: Vec<Planes>,
}

/// Linear values of the 256 opaque 8-bit sRGB levels, computed by `yuvxyb` itself.
fn srgb_levels() -> &'static [f32; 256] {
    static TABLE: OnceLock<[f32; 256]> = OnceLock::new();
    TABLE.get_or_init(|| {
        let gray: Vec<[f32; 3]> = (0..=255u8).map(|c| [f32::from(c) / 255.0; 3]).collect();
        let rgb = Rgb::new(gray, 256, 1, TransferCharacteristic::SRGB, ColorPrimaries::BT709)
            .expect("256 pixels make a 256 x 1 image");
        let linear = LinearRgb::try_from(rgb).expect("sRGB converts to linear");
        std::array::from_fn(|c| linear.data()[c][0])
    })
}

/// Converts to linear RGB in parallel bands, with transparent pixels over `BACKDROP`.
fn linear_of(img: &RgbaImage) -> Option<Linear> {
    let (width, height) = (img.width() as usize, img.height() as usize);
    let raw = img.as_raw();
    let levels = srgb_levels();
    let bands: Vec<Vec<[f32; 3]>> = (0..height.div_ceil(BAND_ROWS))
        .into_par_iter()
        .map(|band| {
            let rows = BAND_ROWS.min(height - band * BAND_ROWS);
            let (pixels, _) = raw[band * BAND_ROWS * width * 4..][..rows * width * 4].as_chunks::<4>();
            if pixels.iter().all(|p| p[3] == u8::MAX) {
                return Some(
                    pixels
                        .iter()
                        .map(|p| [levels[p[0] as usize], levels[p[1] as usize], levels[p[2] as usize]])
                        .collect(),
                );
            }
            let data: Vec<[f32; 3]> = pixels
                .iter()
                .map(|p| {
                    let alpha = f32::from(p[3]) / 255.0;
                    let mix = |c: u8| (f32::from(c) * alpha + BACKDROP * (1.0 - alpha)) / 255.0;
                    [mix(p[0]), mix(p[1]), mix(p[2])]
                })
                .collect();
            let rgb = Rgb::new(data, width, rows, TransferCharacteristic::SRGB, ColorPrimaries::BT709).ok()?;
            Some(LinearRgb::try_from(rgb).ok()?.into_data())
        })
        .collect::<Option<_>>()?;
    Some(Linear { data: bands.concat(), width, height })
}

fn downscale_by_2(input: &Linear) -> Linear {
    const SCALE: usize = 2;
    let (in_w, in_h) = (input.width, input.height);
    let out_w = in_w.div_ceil(SCALE);
    let out_h = in_h.div_ceil(SCALE);
    let normalize = 1f32 / (SCALE * SCALE) as f32;
    let mut data = vec![[0.0f32; 3]; out_w * out_h];
    data.par_chunks_mut(out_w).enumerate().for_each(|(oy, row)| {
        for (ox, out) in row.iter_mut().enumerate() {
            for (c, out) in out.iter_mut().enumerate() {
                let mut sum = 0f32;
                for iy in 0..SCALE {
                    for ix in 0..SCALE {
                        let x = (ox * SCALE + ix).min(in_w - 1);
                        let y = (oy * SCALE + iy).min(in_h - 1);
                        sum += input.data[y * in_w + x][c];
                    }
                }
                *out = sum * normalize;
            }
        }
    });
    Linear { data, width: out_w, height: out_h }
}

/// XYB planes of `rows` rows of linear RGB, in the positive range the metric works in.
fn xyb_planes(linear: &[[f32; 3]], width: usize, rows: usize) -> [Vec<f32>; 3] {
    let xyb = Xyb::from(LinearRgb::new(linear.to_vec(), width, rows).expect("rows and data agree"));
    let mut planes = [vec![0f32; width * rows], vec![0f32; width * rows], vec![0f32; width * rows]];
    for (i, pix) in xyb.data().iter().enumerate() {
        // Get all components in more or less 0..1 range.
        planes[0][i] = fma(pix[0], 14.0, 0.42);
        planes[1][i] = pix[1] + 0.01;
        planes[2][i] = (pix[2] - pix[1]) + 0.55;
    }
    planes
}

/// Calls `visit` with each scale of the linear pyramid of `image` that the metric scores. A scale is
/// scored when the one before it was at least 8 pixels on both sides, as the original does.
fn pyramid(image: Linear, mut visit: impl FnMut(usize, &Linear)) {
    let mut current = image;
    for scale in 0..NUM_SCALES {
        if scale > 0 {
            if current.width < 8 || current.height < 8 {
                break;
            }
            current = downscale_by_2(&current);
        }
        visit(scale, &current);
    }
}

impl Reference {
    /// Prepares `image` as a reference. Images with a side under 8 pixels score 0 against anything.
    pub fn new(image: &RgbaImage) -> Self {
        let (width, height) = (image.width() as usize, image.height() as usize);
        let mut scales = Vec::new();
        let linear = if width >= 8 && height >= 8 { linear_of(image) } else { None };
        if let Some(linear) = linear {
            pyramid(linear, |_, level| {
                let bands: Vec<[Vec<f32>; 3]> = (0..level.height.div_ceil(BAND_ROWS))
                    .into_par_iter()
                    .map(|band| {
                        let y0 = band * BAND_ROWS;
                        let rows = BAND_ROWS.min(level.height - y0);
                        xyb_planes(&level.data[y0 * level.width..(y0 + rows) * level.width], level.width, rows)
                    })
                    .collect();
                let planes = std::array::from_fn(|c| bands.iter().flat_map(|b| b[c].iter().copied()).collect());
                scales.push(Planes { width: level.width, height: level.height, planes });
            });
        }
        Self { width, height, scales }
    }

    /// SSIMULACRA2 of `distorted` against this reference: 100 is identical. Dimensions that differ, or a
    /// side under 8 pixels, score 0.
    pub fn score(&self, distorted: &RgbaImage) -> f64 {
        if self.scales.is_empty()
            || distorted.width() as usize != self.width
            || distorted.height() as usize != self.height
        {
            return 0.0;
        }
        let Some(linear) = linear_of(distorted) else {
            return 0.0;
        };
        let mut scales = Vec::new();
        pyramid(linear, |scale, level| scales.push(scale_sums(&self.scales[scale], level)));
        weighted_score(&scales)
    }
}

/// Sums over one scale, before normalisation.
#[derive(Clone, Copy, Default)]
struct Sums {
    ssim: [f64; 6],
    edge: [f64; 12],
}

impl Sums {
    fn add(mut self, other: Self) -> Self {
        self.ssim.iter_mut().zip(other.ssim).for_each(|(a, b)| *a += b);
        self.edge.iter_mut().zip(other.edge).for_each(|(a, b)| *a += b);
        self
    }
}

/// The partial sums of every band of one scale, added.
fn scale_sums(reference: &Planes, distorted: &Linear) -> ScaleScores {
    let (width, height) = (reference.width, reference.height);
    let sums = (0..height.div_ceil(BAND_ROWS))
        .into_par_iter()
        .map(|band| band_sums(reference, distorted, band * BAND_ROWS, (band * BAND_ROWS + BAND_ROWS).min(height)))
        .reduce(Sums::default, Sums::add);
    let one_per_pixels = 1.0f64 / (width * height) as f64;
    let mut out = ScaleScores::default();
    for c in 0..3 {
        out.ssim[c * 2] = one_per_pixels * sums.ssim[c * 2];
        out.ssim[c * 2 + 1] = (one_per_pixels * sums.ssim[c * 2 + 1]).sqrt().sqrt();
        for k in 0..2 {
            out.edge[c * 4 + k * 2] = one_per_pixels * sums.edge[c * 4 + k * 2];
            out.edge[c * 4 + k * 2 + 1] = (one_per_pixels * sums.edge[c * 4 + k * 2 + 1]).sqrt().sqrt();
        }
    }
    out
}

/// One scale's normalised scores: per channel the 1-norm and 4-norm of the SSIM map, and of the
/// artifact and detail-loss edge maps.
#[derive(Clone, Copy, Default)]
struct ScaleScores {
    ssim: [f64; 6],
    edge: [f64; 12],
}

/// Rows `y0..y1` of one scale: XYB of the distorted rows, the five blurred quantities and the sums.
fn band_sums(reference: &Planes, distorted: &Linear, y0: usize, y1: usize) -> Sums {
    let width = reference.width;
    let height = reference.height;
    // Rows the blur of rows y0..y1 reads; everything outside is zero for the recursion.
    let lo = y0.saturating_sub(RADIUS);
    let hi = (y1 + RADIUS - 1).min(height);
    let rows = hi - lo;
    let img2 = xyb_planes(&distorted.data[lo * width..hi * width], width, rows);
    let mut sums = Sums::default();
    let mut product = vec![0f32; width * rows];
    let band = Band { width, lo, hi, y0, y1 };
    for c in 0..3 {
        let img1 = &reference.planes[c][lo * width..hi * width];
        let img2 = &img2[c];
        let mu1 = band.blur(img1);
        let mu2 = band.blur(img2);
        multiply(img1, img1, &mut product);
        let s11 = band.blur(&product);
        multiply(img2, img2, &mut product);
        let s22 = band.blur(&product);
        multiply(img1, img2, &mut product);
        let s12 = band.blur(&product);

        let first = (y0 - lo) * width;
        let img1 = &img1[first..first + (y1 - y0) * width];
        let img2 = &img2[first..first + (y1 - y0) * width];
        const C2: f32 = 0.0009f32;
        let (mut ssim, mut edge) = ([0.0f64; 2], [0.0f64; 4]);
        for i in 0..img1.len() {
            let (m1, m2) = (mu1[i], mu2[i]);
            let mu11 = m1 * m1;
            let mu22 = m2 * m2;
            let mu12 = m1 * m2;
            let mu_diff = m1 - m2;
            // The denominator of the original SSIM luma term is dropped; see the ssimulacra2 source.
            let num_m = fma(mu_diff, -mu_diff, 1.0f32);
            let num_s = fma(2f32, s12[i] - mu12, C2);
            let denom_s = (s11[i] - mu11) + (s22[i] - mu22) + C2;
            let d = (1.0f64 - f64::from((num_m * num_s) / denom_s)).max(0.0);
            ssim[0] += d;
            ssim[1] += d.powi(4);

            let d1: f64 = (1.0 + f64::from((img2[i] - m2).abs())) / (1.0 + f64::from((img1[i] - m1).abs())) - 1.0;
            // d1 > 0: distorted has an edge where the original is smooth (ringing, banding, blocking).
            let artifact = d1.max(0.0);
            edge[0] += artifact;
            edge[1] += artifact.powi(4);
            // d1 < 0: the original has an edge where the distorted is smooth (blurring, smearing).
            let detail_lost = (-d1).max(0.0);
            edge[2] += detail_lost;
            edge[3] += detail_lost.powi(4);
        }
        sums.ssim[c * 2..c * 2 + 2].copy_from_slice(&ssim);
        sums.edge[c * 4..c * 4 + 4].copy_from_slice(&edge);
    }
    sums
}

fn multiply(a: &[f32], b: &[f32], out: &mut [f32]) {
    for ((&a, &b), o) in a.iter().zip(b).zip(out.iter_mut()) {
        *o = a * b;
    }
}

/// The geometry of a band: image `width`, plane rows `lo..hi` present, rows `y0..y1` wanted.
struct Band {
    width: usize,
    lo: usize,
    hi: usize,
    y0: usize,
    y1: usize,
}

impl Band {
    /// Gaussian blur of the plane rows `lo..hi`, returning rows `y0..y1`.
    fn blur(&self, plane: &[f32]) -> Vec<f32> {
        let mut horizontal = vec![0f32; plane.len()];
        for (input, output) in plane.chunks_exact(self.width).zip(horizontal.chunks_exact_mut(self.width)) {
            horizontal_row(input, output, self.width);
        }
        let mut out = vec![0f32; (self.y1 - self.y0) * self.width];
        let mut x = 0;
        while x + COLUMNS <= self.width {
            self.vertical::<COLUMNS>(&horizontal, &mut out, x);
            x += COLUMNS;
        }
        while x < self.width {
            self.vertical::<1>(&horizontal, &mut out, x);
            x += 1;
        }
        out
    }

    /// Vertical pass over `N` columns starting at `x`. The recursion starts `2 * RADIUS - 1` rows above the
    /// first wanted row, with the rows above `lo` read as zero.
    fn vertical<const N: usize>(&self, input: &[f32], out: &mut [f32], x: usize) {
        let big_n = RADIUS as isize;
        let zeroes = [0f32; N];
        // The state of the three resonators for the last three rows, used in turn: this row is written
        // over the oldest.
        let mut state = [[[0f32; N]; 3]; 3];
        let row = |r: isize| -> &[f32; N] {
            if r < self.lo as isize || r >= self.hi as isize {
                &zeroes
            } else {
                input[(r as usize - self.lo) * self.width + x..][..N].try_into().expect("N columns")
            }
        };
        let mut n = self.y0 as isize - 2 * big_n + 1;
        let mut slot = 0usize;
        while n < self.y1 as isize {
            let (top, bottom) = (row(n - big_n - 1), row(n + big_n - 1));
            let (prev, prev2) = (state[(slot + 2) % 3], state[(slot + 1) % 3]);
            let cur = &mut state[slot];
            let mut sums = [0f32; N];
            for i in 0..N {
                let sum = top[i] + bottom[i];
                let out1 = fma(prev[0][i], VERT_MUL_PREV_1, prev2[0][i]);
                let out3 = fma(prev[1][i], VERT_MUL_PREV_3, prev2[1][i]);
                let out5 = fma(prev[2][i], VERT_MUL_PREV_5, prev2[2][i]);
                let out1 = fma(sum, VERT_MUL_IN_1, -out1);
                let out3 = fma(sum, VERT_MUL_IN_3, -out3);
                let out5 = fma(sum, VERT_MUL_IN_5, -out5);
                cur[0][i] = out1;
                cur[1][i] = out3;
                cur[2][i] = out5;
                sums[i] = out1 + out3 + out5;
            }
            if n >= self.y0 as isize {
                out[(n as usize - self.y0) * self.width + x..][..N].copy_from_slice(&sums);
            }
            slot = (slot + 1) % 3;
            n += 1;
        }
    }
}

/// Horizontal pass of the recursive Gaussian on one row (Charalampidis 2016, truncated cosines).
fn horizontal_row(input: &[f32], output: &mut [f32], width: usize) {
    let big_n = RADIUS as isize;
    let (mut prev_1, mut prev_3, mut prev_5) = (0f32, 0f32, 0f32);
    let (mut prev2_1, mut prev2_3, mut prev2_5) = (0f32, 0f32, 0f32);
    let mut n = (-big_n) + 1;
    while n < width as isize {
        let left = n - big_n - 1;
        let right = n + big_n - 1;
        let left_val = if left >= 0 { input[left as usize] } else { 0f32 };
        let right_val = if right < width as isize { input[right as usize] } else { 0f32 };
        let sum = left_val + right_val;

        let mut out_1 = sum * MUL_IN_1;
        let mut out_3 = sum * MUL_IN_3;
        let mut out_5 = sum * MUL_IN_5;

        out_1 = fma(MUL_PREV2_1, prev2_1, out_1);
        out_3 = fma(MUL_PREV2_3, prev2_3, out_3);
        out_5 = fma(MUL_PREV2_5, prev2_5, out_5);
        prev2_1 = prev_1;
        prev2_3 = prev_3;
        prev2_5 = prev_5;

        out_1 = fma(MUL_PREV_1, prev_1, out_1);
        out_3 = fma(MUL_PREV_3, prev_3, out_3);
        out_5 = fma(MUL_PREV_5, prev_5, out_5);
        prev_1 = out_1;
        prev_3 = out_3;
        prev_5 = out_5;

        if n >= 0 {
            output[n as usize] = out_1 + out_3 + out_5;
        }
        n += 1;
    }
}

/// The weighted sum of the 108 sub-scores, mapped to the 0 to 100 scale.
fn weighted_score(scales: &[ScaleScores]) -> f64 {
    let mut ssim = 0.0f64;
    let mut i = 0usize;
    for c in 0..3 {
        for scale in scales {
            for n in 0..2 {
                ssim = WEIGHT[i].mul_add(scale.ssim[c * 2 + n].abs(), ssim);
                i += 1;
                ssim = WEIGHT[i].mul_add(scale.edge[c * 4 + n].abs(), ssim);
                i += 1;
                ssim = WEIGHT[i].mul_add(scale.edge[c * 4 + n + 2].abs(), ssim);
                i += 1;
            }
        }
    }

    ssim *= 0.956_238_261_683_484_4_f64;
    ssim = (6.248_496_625_763_138e-5 * ssim * ssim)
        .mul_add(ssim, 2.326_765_642_916_932f64.mul_add(ssim, -0.020_884_521_182_843_837 * ssim * ssim));

    if ssim > 0.0f64 { ssim.powf(0.627_633_646_783_138_7).mul_add(-10.0f64, 100.0f64) } else { 100.0f64 }
}

